   public void setupAnim(WitherStormRenderState state) {
      this.root.getAllParts().forEach(ModelPart::resetPose);
      if (this.revealProgress < 1.0F) {
         int shown = Mth.ceil(Mth.clamp(this.revealProgress, 0.0F, 1.0F) * (float)this.chain.size());

         for (int i = 0; i < this.chain.size(); i++) {
            this.chain.get(i).visible = i < shown;
         }
      } else {
         for (ModelPart bone : this.chain) {
            bone.visible = true;
         }
      }

      float grown = 1.0F;
      if (this.sprout >= 0.0F) {
         float p = Mth.clamp(this.sprout, 0.0F, 1.0F);
         grown = p * p * (3.0F - 2.0F * p);
         float s = 0.02F + 0.98F * grown;
         this.chain.get(0).xScale = s;
         this.chain.get(0).yScale = s;
         this.chain.get(0).zScale = s;
         float curl = (1.0F - grown) * 0.42F;
         if (curl > 1.0E-4F) {
            for (int i = 0; i < this.chain.size(); i++) {
               ModelPart var10000 = this.chain.get(i);
               var10000.zRot = var10000.zRot + curl * (0.4F + 0.6F * (float)i / (float)this.chain.size());
            }
         }
      }

      float t = state.idleTimeTicks * 0.06F;

      for (int i = 0; i < this.chain.size(); i++) {
         ModelPart bone = this.chain.get(i);
         float phase = t - (float)i * 0.5F;
         float amp = (0.06F + 0.07F * ((float)i / (float)this.chain.size())) * grown;
         bone.xRot = bone.xRot + Mth.sin((double)phase) * amp;
         bone.yRot = bone.yRot + Mth.cos((double)(phase * 0.8F + 0.5F)) * amp * 0.7F;
      }
   }

